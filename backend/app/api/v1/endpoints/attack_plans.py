import uuid
from datetime import datetime, timezone
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from app.database.session import get_db
from app.models.security_test import AttackPlan
from app.models.scan import Scan
from shared.contracts.models import AttackPlanRequest, AttackPlanResponse, AttackScenario
from shared.enums.common import HttpMethod, SafetyClassification

router = APIRouter()


@router.get("/", response_model=List[AttackPlanResponse])
async def list_attack_plans(
    app_id: Optional[uuid.UUID] = None,
    scan_id: Optional[uuid.UUID] = None,
    db: AsyncSession = Depends(get_db)
):
    """List generated autonomous attack plans."""
    query = select(AttackPlan)
    if app_id:
        query = query.where(AttackPlan.application_id == app_id)
    if scan_id:
        query = query.where(AttackPlan.scan_id == scan_id)
    result = await db.execute(query)
    plans = result.scalars().all()
    return plans


@router.post("/", response_model=AttackPlanResponse, status_code=status.HTTP_201_CREATED)
async def generate_attack_plan(
    plan_req: AttackPlanRequest,
    db: AsyncSession = Depends(get_db)
):
    """Generate an AI-driven attack test plan for review and policy validation."""
    result = await db.execute(select(Scan).where(Scan.id == plan_req.scan_id))
    scan = result.scalars().first()
    if not scan:
        raise HTTPException(status_code=404, detail="Scan not found")

    # Initial plan structure generated by Planning Agent
    initial_scenarios = [
        {
            "scenario_id": f"sc-{uuid.uuid4().hex[:8]}",
            "name": "BOLA / IDOR Resource Ownership Check",
            "category": "BOLA",
            "target_endpoint": "/api/v1/users/{id}",
            "method": "GET",
            "hypothesis": "Verify if authenticated tenant user A can access tenant user B object",
            "safety_classification": "SAFE_READ_ONLY",
            "preconditions": ["Two valid synthetic user tokens"],
        }
    ]

    new_plan = AttackPlan(
        scan_id=plan_req.scan_id,
        application_id=plan_req.application_id,
        status="DRAFT",
        scenarios=initial_scenarios,
    )
    db.add(new_plan)
    await db.commit()
    await db.refresh(new_plan)
    return new_plan


@router.post("/{plan_id}/approve", response_model=AttackPlanResponse)
async def approve_attack_plan(
    plan_id: uuid.UUID,
    db: AsyncSession = Depends(get_db)
):
    """Approve an attack plan for execution under the Central Safety Policy."""
    result = await db.execute(select(AttackPlan).where(AttackPlan.id == plan_id))
    plan = result.scalars().first()
    if not plan:
        raise HTTPException(status_code=404, detail="Attack plan not found")

    plan.status = "APPROVED"
    plan.approved_at = datetime.now(timezone.utc)
    await db.commit()
    await db.refresh(plan)
    return plan

